#!/usr/bin/env node
/**
 * Regenerates docs/DATABASE.md from src/lib/schema/.
 *
 *   npm run docs:schema
 *
 * The schema definition is the single source of truth; this keeps the
 * documentation from drifting away from it, which hand-written table lists
 * always eventually do.
 */

import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const SCHEMA_DIR = join(ROOT, "src", "lib", "schema");
const OUT = join(ROOT, "docs", "DATABASE.md");

const GROUP_TITLES = {
  platform: "Platform & tenants",
  identity: "Identity, RBAC & audit",
  hr: "Human resources",
  fleet: "Fleet & vehicles",
  procurement: "Procurement & supply chain",
  crm: "Sales, CRM & field operations",
  finance: "Finance & accounting",
  workplace: "Facilities, assets & tasks",
  telemetry: "GPS telemetry & geofencing",
};

function parseTables(text) {
  const tables = [];
  const re = /CREATE TABLE IF NOT EXISTS\s+(\w+)\s*\(([\s\S]*?)\n\s*\)`/g;
  let m;
  while ((m = re.exec(text))) {
    const [, name, body] = m;
    const columns = [];
    for (const raw of body.split("\n")) {
      const line = raw.trim().replace(/,$/, "");
      if (!line || line.startsWith("--")) continue;
      // Skip table-level constraints; only column definitions are documented.
      if (/^(CONSTRAINT|UNIQUE|PRIMARY KEY|CHECK|FOREIGN KEY)\b/i.test(line)) continue;
      const parts = line.split(/\s+/);
      if (parts.length < 2) continue;
      const [column, ...rest] = parts;
      if (!/^[a-z_][a-z0-9_]*$/.test(column)) continue;
      columns.push({ column, definition: rest.join(" ") });
    }
    tables.push({ name, columns, tenantScoped: /\btenant_id\b/.test(body) });
  }
  return tables;
}

function parseIndexes(text) {
  const out = [];
  const re = /CREATE (?:UNIQUE )?INDEX IF NOT EXISTS\s+(\w+)\s*\n?\s*ON\s+([\s\S]*?)`/g;
  let m;
  while ((m = re.exec(text))) {
    out.push({ name: m[1], on: m[2].replace(/\s+/g, " ").trim() });
  }
  return out;
}

async function main() {
  const files = (await readdir(SCHEMA_DIR)).filter(
    (f) => f.endsWith(".ts") && f !== "index.ts"
  );

  const groups = [];
  let indexes = [];
  let tableCount = 0;
  let scopedCount = 0;

  for (const key of Object.keys(GROUP_TITLES)) {
    const file = files.find((f) => f === `${key}.ts`);
    if (!file) continue;
    const text = await readFile(join(SCHEMA_DIR, file), "utf8");
    const tables = parseTables(text);
    indexes.push(...parseIndexes(text));
    tableCount += tables.length;
    scopedCount += tables.filter((t) => t.tenantScoped).length;
    groups.push({ key, title: GROUP_TITLES[key], file, tables });
  }

  const idxText = await readFile(join(SCHEMA_DIR, "indexes.ts"), "utf8").catch(() => "");
  indexes.push(...parseIndexes(idxText));

  const lines = [
    "<!-- Generated by scripts/gen-schema-docs.mjs from src/lib/schema/.",
    "     Run `npm run docs:schema` after a schema change. Do not edit by hand. -->",
    "",
    "# Database schema",
    "",
    `${tableCount} tables, ${scopedCount} of them tenant-scoped, plus ${indexes.length} indexes.`,
    "",
    "The schema is defined once, in `src/lib/schema/`, as an ordered list of",
    "idempotent statements. There is no migration runner: the same list creates a",
    "fresh database and brings a deployed one up to date on every cold start.",
    "",
    "A **tenant-scoped** table carries a `tenant_id` column, and every query against",
    "one must filter by the tenant id taken from the session.",
    "`npm run check:tenancy` enforces that mechanically.",
    "",
    "## Contents",
    "",
    ...groups.map((g) => `- [${g.title}](#${g.title.toLowerCase().replace(/[^a-z0-9]+/g, "-")})`),
    "",
  ];

  for (const group of groups) {
    lines.push(`## ${group.title}`, "", `Defined in \`src/lib/schema/${group.file}\`.`, "");
    for (const table of group.tables) {
      lines.push(
        `### \`${table.name}\`${table.tenantScoped ? " · tenant-scoped" : ""}`,
        "",
        "| Column | Definition |",
        "|---|---|",
        ...table.columns.map((c) => `| \`${c.column}\` | ${c.definition} |`),
        ""
      );
    }
  }

  lines.push(
    "## Indexes",
    "",
    "| Index | On |",
    "|---|---|",
    ...indexes.map((i) => `| \`${i.name}\` | ${i.on} |`),
    ""
  );

  await writeFile(OUT, lines.join("\n"), "utf8");
  console.log(`docs:schema — wrote ${OUT} (${tableCount} tables, ${indexes.length} indexes)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
