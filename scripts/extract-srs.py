"""Re-generate docs/SRS.md from the original Word SRS kept in docs/.
Run: python -I scripts/extract-srs.py
Keeps the markdown reference in sync with the authoritative .docx."""
import html
import re
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCX = ROOT / "docs" / "Master_Office_Management_System_SRS_v2.docx"
OUT = ROOT / "docs" / "SRS.md"

with zipfile.ZipFile(DOCX) as z:
    xml = z.read("word/document.xml").decode("utf-8")

# Each <w:p> is a paragraph, each <w:tr> a table row, each <w:tc> a cell.
xml = re.sub(r"</w:p>", "\n", xml)
xml = re.sub(r"</w:tr>", "\n", xml)
xml = re.sub(r"</w:tc>", "\t", xml)
text = html.unescape(re.sub(r"<[^>]+>", "", xml))
# The Word bullets come through as a stray private-use glyph.
text = text.replace("", "\n- ").replace("�", "\n- ")

lines = []
for raw in text.split("\n"):
    line = raw.strip().strip("\t").rstrip("\t ")
    if not line:
        continue
    if "\t" in line:  # table row
        cells = [c.strip() for c in line.split("\t") if c.strip()]
        line = "| " + " | ".join(cells) + " |"
    elif re.match(r"^\d+(\.\d+)*\s", line):  # numbered heading
        depth = line.split(" ")[0].count(".") + 2
        line = "#" * min(depth, 6) + " " + line
    lines.append(line)

OUT.write_text(
    "<!-- Generated by scripts/extract-srs.py from "
    "docs/Master_Office_Management_System_SRS_v2.docx. Do not edit by hand. -->\n\n"
    + "\n\n".join(lines)
    + "\n",
    encoding="utf-8",
)
print(f"wrote {OUT} ({len(lines)} blocks)")
